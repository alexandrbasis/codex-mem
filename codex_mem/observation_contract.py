"""Shared evidence requirements for generated observation classifications."""

OBSERVATION_CLASSIFICATION_CONTRACT = (
    "Observation type is an application classification inferred from the evidenced work or finding. "
    "The source need not literally assign or name the category. "
    "A finding or observed evidence limitation can be discovery without completion. "
    "The category bugfix requires evidence of an actual correction, not a still-failing test; "
    "record an unresolved failure as discovery with its open work. "
    "The category decision requires an accepted choice with rationale, not an unaccepted suggestion. "
    "The categories feature, refactor and change require an observed change, never just an implementation request. "
    "Generic topic and concept labels require topical fit. Any label or category implying "
    "completion, termination, failure, identity, quantity or another factual assertion requires "
    "the same scoped evidence, attribution and uncertainty as prose. "
    "A title stating a test or measurement result must retain the tested scope when omitting "
    "it would imply a general product property. Use a topical title if the necessary qualifier "
    "does not fit clearly. "
    "Concept labels are optional; examples are not default values. When a note states that "
    "the cause or remedy remains unknown, prefer a label describing the failure or investigation. "
    "Use problem-solution only when the evidence links a problem to a proposed or actual remedy, "
    "preserving that remedy's unverified or proposed status in the note. "
    "No material field is exempt from factual support. "
    "Preserve the source's scope and modality in every field: a preference is not a requirement, "
    "discussion is not agreement, and a recalled possible limitation is not an established limitation. "
    "Keep these qualifiers next to the claim rather than relying on a later general disclaimer. "
    "Preserve entity relationships and quantifiers: a specific program of a selected account "
    "does not establish every program or every account. Do not broaden one instance into a rule. "
    "Keep distinct domain terms distinct unless the evidence establishes their equivalence. "
    "When a synonym or translation could change the meaning, retain the source term with attribution. "
    "Copy concrete test names and other identifiers exactly from the evidence for the stated "
    "result. Do not replace them with similarly named targets from a command or earlier record. "
    "If the command and result name different targets, preserve the discrepancy instead of "
    "silently treating the names as equivalent. "
)

OBSERVATION_FILE_EVIDENCE_CONTRACT = (
    "File paths carry operation claims in files_read and files_modified. "
    "Use files_read only when evidence establishes that the file's contents were read or inspected, "
    "and files_modified only when evidence establishes an actual edit. A path mentioned in a "
    "request, command, traceback or test result does not by itself establish either operation. "
    "Executing a file does not establish inspection of its contents. Preserve relevant referenced "
    "paths in the body or facts when no read or edit is established; leave unsupported file arrays empty. "
    "A content search that returns matching lines establishes limited inspection of that file, "
    "not review of the whole file. A filename-only listing establishes no content inspection. "
)

SOURCE_CONTENT_EVIDENCE_CONTRACT = (
    "Keep the content of each source separate from context used to interpret it. "
    "A claim that a particular message, document or result states X requires X in that source. "
    "An earlier record or another speaker's report cannot add words, values, durations, "
    "identities or terms to the claimed source, even when those details plausibly explain it. "
    "History can resolve an unambiguous reference, but label the origin of any added detail: "
    "the earlier offer said X; the new reply said Y. A contextual synthesis is not a claim "
    "that the new reply itself stated both X and Y. For example, if an earlier offer says "
    "39 units for six months and a later reply says only afterward 49, the later reply does "
    "not itself state 39 or six months. Describe those as earlier terms when they are relevant. "
    "Apply this source boundary to titles, prose, structured facts and summaries alike. "
)

SUMMARY_FIELD_EVIDENCE_CONTRACT = (
    "Populate request only from an evidenced actual user request; otherwise use null. "
    "A drafted or sent artifact, tool action or assistant report of work does not by itself "
    "establish the original user request or authorization. "
    "Keep user feedback separate from the assistant's interpretation or commitment. "
    "Do not attribute an assistant-proposed preference, rule or plan to the user without "
    "user evidence for that specific claim. Acknowledged feedback does not by itself "
    "establish an accepted decision or a completed change in future practice. "
    "Preserve where each statement was made. A link to a document or conversation does not "
    "place the user's message or the assistant's response inside that linked source. "
    "Use an empty string for next_steps unless the sources establish explicitly requested "
    "unfinished work or a plan or proposal. A bounded remainder of an evidenced request "
    "can remain without inventing an actor commitment. Record a relevant unresolved external "
    "condition in learned or notes at its evidenced scope; it does not by itself establish "
    "a plan to wait, review, approve or follow up. Label a proposal only when the sources "
    "propose it. Preserve attribution, uncertainty and planned-versus-completed scope. "
    "Keep all required keys, any required summary and its supported fields. Use permitted "
    "null or empty values for unsupported fields instead of inventing content to fill them. "
)
